#!/usr/bin/env python3
"""Round-2 contracts (2026-11-01): calibrated load axis + multi-seed matrix.

Phase A (this commit): ONLY the calibration contract is frozen, because the
global offered loads for regimes A/B/C/D must be chosen from MEASURED
utilisation/slack on the critical corridor, not from a configured Mbps label.
Phase B (after calibration): the matrix contract is generated by the same
script with the measured loads and frozen cell ids; it is committed and
published in a second release.

Run from the worktree root:
    python3 ANALYSIS/SIM-QUAL-20261031/make_round2_contracts.py calib
    python3 ANALYSIS/SIM-QUAL-20261031/make_round2_contracts.py matrix \
        --load-a 85 --load-b 145 --load-c 160 --load-d 140 \
        --burst-mult 1.6 --burst-start 8.0 --burst-duration 0.5
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

CONTRACT_DIR = Path("EXPERIMENTS/contracts")
BASE_PROFILE = "CODE/leo_sim/profiles/ta_pilot_140_adv1.yaml"

SITES = {
    "tokyo": [35.68, 139.69],
    "singapore": [1.35, 103.82],
    "london": [51.51, -0.13],
    "newyork": [40.71, -74.01],
    "saopaulo": [-23.55, -46.63],
    "lagos": [6.52, 3.38],
}
OD_WEIGHTS = {}
_rest = 0.30 / 29.0
for _src in SITES:
    for _dst in SITES:
        if _src == _dst:
            continue
        key = f"{_src},{_dst}"
        OD_WEIGHTS[key] = 0.7 if key == "tokyo,singapore" else _rest

DIAGNOSTICS_FULL = {
    "control_audit": False,
    "decisions": True,
    "timeline": False,
    "truth_probe": True,
    "truth_probe_max": 200_000,
    "truth_probe_stride": 1,
}
DIAGNOSTICS_CALIB = {
    "control_audit": False,
    "decisions": True,
    "timeline": False,
    "truth_probe": False,
    "truth_probe_max": 200_000,
    "truth_probe_stride": 1,
}


def trace_program(total_mbps: float, seed: int, pulse: dict | None = None) -> dict:
    program = {
        "schema": "scene-trace-program/v1",
        "model": "s1_stationary",
        "seed": int(seed),
        "cells": SITES,
        "od_weights": OD_WEIGHTS,
        "total_mbps": float(total_mbps),
        "packet_bits": 1_000_000,
        "emission_start_s": 4.0,
        "emission_end_s": 14.0,
    }
    if pulse is not None:
        program["pulse"] = dict(pulse)
    return program


def base_overrides(*, advert_s: float, ctrl_bits: int, vis_k: int,
                   policy: str, eta_s: float, alpha: float) -> dict:
    return {
        "control_plane": {
            "advertise_interval_s": float(advert_s),
            "vis_k": int(vis_k),
            "packet_bits": int(ctrl_bits),
        },
        "demand": {
            "emission_start_s": 4.0,
            "emission_end_s": 14.0,
            "packet_bits": 1_000_000,
        },
        "execution": {
            "compute_delay_s": 0.0,
            "compute_servers_per_satellite": 0,
            "max_packets": 40_000,
        },
        "links": {
            "isl_rate_mbps": 100.0,
            "isl_queue_bits": 64_000_000,
            "rate_model": "constant",
        },
        "scenario": {"duration_s": 20.0},
        "time_alignment": {
            "predictor": "hold_last",
            "state_policy": policy,
            # config refuses a nonzero eta on a non-hysteresis policy (an
            # unused parameter would silently not enter the run)
            "hysteresis_eta_s": (float(eta_s)
                                 if policy == "queue_greedy_hysteresis"
                                 else 0.0),
            "ewma_alpha": float(alpha),
        },
    }


def cell(cell_id: str, *, total_mbps: float, seed: int, pulse: dict | None,
         policy: str = "queue_greedy", advert_s: float = 1.0,
         ctrl_bits: int = 8_000, vis_k: int = 3,
         eta_s: float = 0.005, alpha: float = 0.25) -> dict:
    return {
        "id": cell_id,
        "arms": ["now"],
        "overrides": base_overrides(advert_s=advert_s, ctrl_bits=ctrl_bits,
                                    vis_k=vis_k, policy=policy,
                                    eta_s=eta_s, alpha=alpha),
        "trace_program": trace_program(total_mbps, seed, pulse),
    }


def calibration_contract() -> dict:
    cells = []
    # Measured utilisation of the same fixed trace at several global offered
    # loads; the corridor rho/slack of these runs chooses the A/B/C loads.
    for load in (60.0, 70.0, 80.0, 90.0, 100.0, 120.0, 140.0,
                 150.0, 160.0, 165.0):
        cells.append(cell(f"cal-{int(load):03d}", total_mbps=load, seed=7,
                          pulse=None))
    # Pre/post control-plane fix comparison: EXACT copies of the Round-1
    # p1-high-greedy and p2-sync-greedy configurations (same trace, same
    # policy) so control bytes / area / TTL expiry / AoI can be compared and
    # the data plane must stay bit-identical.
    cells.append(cell("pf-high-greedy", total_mbps=120.0, seed=7,
                      pulse={"start_s": 8.0, "duration_s": 0.5,
                             "multiplier": 1.6}))
    cells.append(cell("pf-sync-greedy", total_mbps=120.0, seed=7,
                      pulse={"start_s": 8.0, "duration_s": 0.5,
                             "multiplier": 1.6},
                      advert_s=0.1, ctrl_bits=2_000, vis_k=3))
    return {
        "schema": "load-calibration-contract/v1",
        "base_profile": BASE_PROFILE,
        "deadline_s": 4.0,
        "max_packets": 50_000,
        "max_duration_s": 20.0,
        "diagnostics": DIAGNOSTICS_CALIB,
        "cells": cells,
    }


def matrix_contract(load_a: float, load_b: float, load_c_high: float,
                    load_c_max: float, load_d: float, burst_mult: float,
                    burst_start: float, burst_duration: float) -> dict:
    """Round-2 matrix.

    Regime loads are chosen from the measured calibration curve, not from the
    configured Mbps: A=90 (measured max corridor rho 0.599), B=160 (0.877);
    the near-capacity C candidates are 180 and 200 because realised rho
    saturates sub-linearly for a queue-aware router (the router diverts before
    a link reaches rho~0.95), so both are generated and the measured slack of
    the executed one defines the regime in the analysis.
    """
    burst = {"start_s": burst_start, "duration_s": burst_duration,
             "multiplier": burst_mult}
    policies = {"geom": "geometry", "greedy": "queue_greedy",
                "ewma": "queue_greedy_ewma"}
    cells = []
    # calibration extension: does realised rho keep rising or plateau?
    for load in (load_c_high, load_c_max):
        cells.append(cell(f"cal-{int(load):03d}", total_mbps=load, seed=7,
                          pulse=None))
    # A: stable / slack control (measured rho ~0.6)
    for name in ("geom", "greedy"):
        cells.append(cell(f"m2-a-{name}-s7", total_mbps=load_a, seed=7,
                          pulse=None, policy=policies[name]))
    # B: high but stable (measured rho ~0.88)
    for name, policy in policies.items():
        for seed in (7, 8):
            cells.append(cell(f"m2-b-{name}-s{seed}", total_mbps=load_b,
                              seed=seed, pulse=None, policy=policy))
    # C: near-capacity candidates x three policies x three seeds
    for tag, load in (("c1", load_c_high), ("c2", load_c_max)):
        for name, policy in policies.items():
            for seed in (7, 8, 9):
                cells.append(cell(f"m2-{tag}-{name}-s{seed}",
                                  total_mbps=load, seed=seed, pulse=None,
                                  policy=policy))
    # hysteresis secondary at the near-capacity baseline (all C candidates)
    for tag, load in (("c1", load_c_high), ("c2", load_c_max)):
        cells.append(cell(f"m2-{tag}-hyst-s7", total_mbps=load, seed=7,
                          pulse=None, policy="queue_greedy_hysteresis"))
    # D: short over-critical burst on the B baseline (finite window)
    for name, policy in policies.items():
        cells.append(cell(f"m2-d-{name}-s7", total_mbps=load_d, seed=7,
                          pulse=burst, policy=policy))
    # strong-sync sweep: vis_k=1 keeps only direct-neighbour advertisements
    # (the state a candidate actually needs: the peer's own egress queue), so
    # state freshness is unchanged while 20 ms advertisements stay affordable.
    # All three sync levels share vis_k=1, so the axis is clean.
    for tag, load in (("c1", load_c_high), ("c2", load_c_max)):
        for advert_ms in (1000, 100, 20):
            for name, policy in policies.items():
                cells.append(cell(f"m2-sync{advert_ms:04d}-{tag}-{name}-s7",
                                  total_mbps=load, seed=7, pulse=None,
                                  policy=policy, advert_s=advert_ms / 1000.0,
                                  ctrl_bits=2_000, vis_k=1))
    return {
        "schema": "load-calibration-contract/v1",
        "base_profile": BASE_PROFILE,
        "deadline_s": 4.0,
        "max_packets": 50_000,
        "max_duration_s": 20.0,
        "diagnostics": DIAGNOSTICS_FULL,
        "cells": cells,
    }


def write(document: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(document, indent=1, sort_keys=True) + "\n",
                    encoding="utf-8")
    print(json.dumps({"path": str(path),
                      "cells": [c["id"] for c in document["cells"]]}))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("what", choices=["calib", "matrix"])
    parser.add_argument("--load-a", type=float, default=90.0)
    parser.add_argument("--load-b", type=float, default=160.0)
    parser.add_argument("--load-c-high", type=float, default=180.0)
    parser.add_argument("--load-c-max", type=float, default=200.0)
    parser.add_argument("--load-d", type=float, default=160.0)
    parser.add_argument("--burst-mult", type=float, default=1.6)
    parser.add_argument("--burst-start", type=float, default=8.0)
    parser.add_argument("--burst-duration", type=float, default=0.5)
    args = parser.parse_args()
    if args.what == "calib":
        write(calibration_contract(), CONTRACT_DIR / "sq-calib-20261031.json")
    else:
        write(matrix_contract(args.load_a, args.load_b, args.load_c_high,
                              args.load_c_max, args.load_d, args.burst_mult,
                              args.burst_start, args.burst_duration),
              CONTRACT_DIR / "sq-matrix2-20261031.json")


if __name__ == "__main__":
    main()
