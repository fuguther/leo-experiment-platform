#!/usr/bin/env python3
"""Emit the two probe contracts from the frozen population program.

Contract A (prediction probe, established scene): three cities / six ODs, the
same link, control and routing settings as the distributed scene, plus the
same-run truth probe.  Its purpose is to produce prediction records and the
truth at the SAME evaluation target instant, in ONE run.

Contract B (population probe): the population-weighted trace program
generated by population_od_program.py, with the same probe enabled, so the
population run also carries labels.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE_PROFILE = "CODE/leo_sim/profiles/t1_scene_trunk_v1.yaml"

OVERRIDES = {
    "scenario": {"duration_s": 6.0, "seed": 111},
    "demand": {"packet_bits": 12000, "emission_start_s": 2.0,
               "emission_end_s": 2.35},
    "links": {"isl_rate_mbps": 1000.0, "isl_queue_bits": 20000000,
              "rate_model": "constant"},
    "control_plane": {"advertise_interval_s": 0.05, "vis_k": 2},
    "routing": {"policy": "known_serving"},
    "time_alignment": {"predictor": "hold_last", "history_limit": 8,
                       "state_source": "advertised"},
}


def contract(cell_id: str, trace_program: dict, arms, max_packets: int) -> dict:
    overrides = json.loads(json.dumps(OVERRIDES))
    # The effective execution cap must not exceed the contract cap.
    overrides.setdefault("execution", {})["max_packets"] = max_packets
    return {
        "schema": "load-calibration-contract/v1",
        "base_profile": BASE_PROFILE,
        "deadline_s": 4,
        "max_packets": max_packets,
        "max_duration_s": 60,
        "diagnostics": {"timeline": False, "control_audit": False,
                        "truth_probe": True, "truth_probe_max": 40000},
        "cells": [{
            "id": cell_id,
            "arms": list(arms),
            "trace_program": trace_program,
            "diagnostics": {"timeline": False},
            "overrides": overrides,
        }],
    }


def main() -> int:
    pop = json.loads((HERE / "population_trace_program_2deg_20261019.json")
                     .read_text())
    # A: the established three-city scene, small and fast, with the probe.
    cities = {"beijing": [39.9, 116.4], "london": [51.5, -0.13],
              "newyork": [40.7, -74.0]}
    od = {"beijing,london": 0.25, "beijing,newyork": 0.25,
          "london,beijing": 0.125, "london,newyork": 0.125,
          "newyork,beijing": 0.125, "newyork,london": 0.125}
    scene_a = {"schema": "scene-trace-program/v1", "model": "s1_stationary",
               "cells": cities, "od_weights": od, "packet_bits": 12000,
               "emission_start_s": 2.0, "emission_end_s": 2.35,
               "seed": 111, "total_mbps": 250.0}
    # 250 Mbps over the 0.35 s window is 7292 packets; the cap leaves room for
    # Poisson jitter and is still small enough for a fast probe.
    a = contract("sc-probe-truth-s111", scene_a, ["candidate"], 10000)
    (HERE / "scene_probe_truth_20261019.json").write_text(
        json.dumps(a, indent=1, sort_keys=True) + "\n")
    b = contract("pop-probe-r020-s111", pop, ["candidate"], 20000)
    (HERE / "scene_population_probe_20261019.json").write_text(
        json.dumps(b, indent=1, sort_keys=True) + "\n")
    print(json.dumps({
        "A": {"path": "scene_probe_truth_20261019.json",
              "cell": "sc-probe-truth-s111", "packets": 8000},
        "B": {"path": "scene_population_probe_20261019.json",
              "cell": "pop-probe-r020-s111",
              "od_pairs": len(pop["od_weights"]),
              "cells": len(pop["cells"])},
    }, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
