ROOT = Path(__file__).resolve().parents[2]


def _write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8")


def _canonical_sha(value: object) -> str:
    return hashlib.sha256(
        json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def _refresh_review(root: Path, experiment: Path, finalization_path: Path) -> None:
    finalization = json.loads(finalization_path.read_text(encoding="utf-8"))
    decision_path = root / finalization["decision_path"]
    decision = json.loads(decision_path.read_text(encoding="utf-8"))
    artifact_hashes = {
        str(path.relative_to(root)): file_sha256(path)
        for path in sorted(experiment.rglob("*")) if path.is_file()
    }
    decision["artifact_hashes"] = artifact_hashes
    for reference in decision["applied_review_receipts"]:
        receipt_path = root / reference["path"]
        receipt = json.loads(receipt_path.read_text(encoding="utf-8"))
        receipt["artifact_hashes"] = artifact_hashes
        _write_json(receipt_path, receipt)
        reference["sha256"] = file_sha256(receipt_path)
    _write_json(decision_path, decision)
    rebuilt, errors = evaluate_decision(
        root, root / finalization["brief_path"], decision_path)
    if errors or rebuilt is None:
        raise AssertionError(f"review finalization rebuild failed: {errors}")
    _write_json(finalization_path, rebuilt)


def _copy_compiled_project(root: Path, manifest: dict[str, object]) -> None:
    source_hashes = manifest["scenario_identity"]["source_and_input_sha256"]  # type: ignore[index]
    for raw in source_hashes:
        source = ROOT / raw
        target = root / raw
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
    for relative in (
        "CODE/experiment_platform/authorize_experiment.py",
        "CODE/experiment_platform/compile_experiment.py",
        "CODE/work/finalize_decision.py",
        "CODE/work/work-package.schema.json",
        "CODE/work/review-receipt.schema.json",
        "CODE/work/decision.schema.json",
        "ANALYSIS/claims/claim.schema.json",
    ):
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / relative, target)


def test_real_compile_authorize_analysis_claim_gate_chain_is_replayable() -> None:
    from CODE.experiment_platform.tests.test_authorize_experiment import AuthorizeExperimentTests

    with tempfile.TemporaryDirectory(prefix="paired-analysis-e2e-") as temporary:
        root = Path(temporary)

        # The helper supplies a valid three-role review/finalization scaffold;
        # the experiment itself is freshly generated by the real compiler.
        experiment, finalization_path, authorization_path, _ = (
            AuthorizeExperimentTests().make_fixture(root)
        )
        request = json.loads(
            (ROOT / "EXPERIMENTS/templates/experiment-request.example.json").read_text(encoding="utf-8")
        )
        request["identity"]["experiment_id"] = "EXP-TEST"
        request["design"]["planned_seeds"] = [42]
        request_input = root / "request-input.json"
        _write_json(request_input, request)
        assert compile_request(request_input, experiment) == 0

        manifest_path = experiment / "run-manifest.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        assert manifest["profile_status"] == "REFERENCE_ONLY_NOT_A_PAPER_BASELINE"
        _copy_compiled_project(root, manifest)
        _refresh_review(root, experiment, finalization_path)
        authorization = build_authorization(root, experiment, finalization_path)
        _write_json(authorization_path, authorization)
        assert verify_authorization(root, authorization_path)["status"] == "AUTHORIZED"
        authorization_sha = file_sha256(authorization_path)

        for row, delivery_rate in zip(manifest["planned_runs"], (0.4, 0.6)):
            run = root / "CODE/Results" / row["run_id"]
            (run / "run_trace").mkdir(parents=True)
            (run / "experiment_bundle").mkdir()
            config = json.loads((experiment / row["config_json"]).read_text(encoding="utf-8"))
            _write_json(run / "config_used.json", config)
            (run / "experiment_bundle/summary_metrics.csv").write_text(
                "metric,value\n"
                f"delivery_rate,{delivery_rate}\n"
                "mean_e2e_latency,1.0\n"
                "p95_e2e_latency,1.0\n",
                encoding="utf-8",
            )
            _write_json(run / "run_trace/run_meta.json", {
                "requested_run_id": row["run_id"],
                "config_canonical_sha256": row["config_sha256"],
                "scenario_identity_sha256": _canonical_sha(manifest["scenario_identity"]),
                "launch_nonce": "a" * 32,
                "run_attempt_id": "b" * 32,
                "authorization_sha256": authorization_sha,
                "natural_end": True,
                "interrupted": False,
                "effective_receipt": {
                    "schema": "leo-effective-receipt/v1",
                    "research_eligible": True,
                    "mismatches": [],
                },
            })
            artifact_entries = []
            for raw in manifest["required_artifacts"]:
                if raw == "artifact_manifest.json":
                    continue
                artifact = run / raw
                artifact_entries.append({
                    "path": raw,
                    "size": artifact.stat().st_size,
                    "sha256": file_sha256(artifact),
                })
            _write_json(run / "artifact_manifest.json", {
                "schema": "artifact-manifest/v1",
                "run_id": row["run_id"],
                "config_sha256": row["config_sha256"],
                "required_artifacts": manifest["required_artifacts"],
                "artifacts": artifact_entries,
            })

        analysis_manifest = root / "ANALYSIS/EXP-TEST/analysis-manifest.json"
        command = [
            sys.executable,
            "ANALYSIS/paired_analysis.py",
            "--analysis", "EXPERIMENTS/EXP-TEST/analysis-request.json",
            "--manifest", "EXPERIMENTS/EXP-TEST/run-manifest.json",
            "--authorization", "EXPERIMENTS/EXP-TEST/authorization.json",
        ]
        for row in manifest["planned_runs"]:
            command.extend(["--run", f"{row['run_id']}=CODE/Results/{row['run_id']}"])
        command.extend(["--out", "ANALYSIS/EXP-TEST"])
        cli = subprocess.run(command, cwd=root, text=True, capture_output=True)
        assert cli.returncode == 0, cli.stderr
        assert analysis_manifest.is_file()

        verify_code = (
            "from pathlib import Path; "
            "from ANALYSIS.paired_analysis import verify_persisted_analysis; "
            "ok, errors = verify_persisted_analysis(Path.cwd(), "
            "Path('ANALYSIS/EXP-TEST/analysis-manifest.json')); "
            "print(ok, errors); raise SystemExit(0 if ok else 1)"
        )
        persisted = subprocess.run(
            [sys.executable, "-c", verify_code], cwd=root, text=True, capture_output=True
        )
        assert persisted.returncode == 0, persisted.stdout + persisted.stderr

        reference = {
            "path": str(analysis_manifest.relative_to(root)),
            "sha256": file_sha256(analysis_manifest),
        }
        assert analysis_manifest_is_paper_eligible(root, reference) is False
        persisted_manifest = json.loads(analysis_manifest.read_text(encoding="utf-8"))
        assert persisted_manifest["inputs"]["ANALYSIS/claims/claim.schema.json"] == file_sha256(
            root / "ANALYSIS/claims/claim.schema.json"
        )
